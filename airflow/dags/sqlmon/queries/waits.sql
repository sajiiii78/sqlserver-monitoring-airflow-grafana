SET NOCOUNT ON;
-- Top 25 waits since instance start (cumulative). Extend the benign-wait list to taste.
SELECT TOP (25)
    wait_type, waiting_tasks_count, wait_time_ms, signal_wait_time_ms
FROM sys.dm_os_wait_stats
WHERE wait_time_ms > 0
  AND wait_type NOT LIKE N'%SLEEP%'
  AND wait_type NOT IN (
      N'LAZYWRITER_SLEEP', N'SQLTRACE_BUFFER_FLUSH', N'BROKER_TASK_STOP', N'BROKER_TO_FLUSH',
      N'BROKER_EVENTHANDLER', N'BROKER_RECEIVE_WAITFOR', N'XE_TIMER_EVENT', N'XE_DISPATCHER_WAIT',
      N'XE_LIVE_TARGET_TVF', N'FT_IFTS_SCHEDULER_IDLE_WAIT', N'REQUEST_FOR_DEADLOCK_SEARCH',
      N'CHECKPOINT_QUEUE', N'DIRTY_PAGE_POLL', N'HADR_FILESTREAM_IOMGR_IOCOMPLETION',
      N'WAITFOR', N'LOGMGR_QUEUE', N'ONDEMAND_TASK_QUEUE', N'CLR_AUTO_EVENT', N'CLR_MANUAL_EVENT',
      N'DISPATCHER_QUEUE_SEMAPHORE', N'HADR_WORK_QUEUE', N'HADR_CLUSAPI_CALL', N'HADR_TIMER_TASK',
      N'HADR_LOGCAPTURE_WAIT', N'PWAIT_ALL_COMPONENTS_INITIALIZED',
      N'SQLTRACE_INCREMENTAL_FLUSH_SLEEP', N'WAIT_XTP_OFFLINE_CKPT_NEW_LOG',
      N'PARALLEL_REDO_DRAIN_WORKER', N'PARALLEL_REDO_LOG_CACHE', N'PARALLEL_REDO_TRAN_LIST',
      N'PARALLEL_REDO_WORKER_SYNC', N'PARALLEL_REDO_WORKER_WAIT_WORK')
ORDER BY wait_time_ms DESC;
